"""Calls into Herdr through its CLI, as the plugin docs recommend."""

from __future__ import annotations

import json
import os
import subprocess
from typing import Optional, Tuple

from . import catalog, paths
from .text import plain_label
from .transcripts import SUPPORTED_AGENTS

HERDR = os.environ.get("HERDR_BIN_PATH") or "herdr"


def run_json(*args: str) -> dict:
    result = subprocess.run([HERDR, *args], capture_output=True, text=True, timeout=10)
    if result.returncode != 0:
        raise RuntimeError(result.stderr.strip() or f"herdr {' '.join(args)} failed")
    return json.loads(result.stdout).get("result", {})


def notify(message: str) -> None:
    try:
        subprocess.run([HERDR, "notification", "show", "Speak", "--body", message, "--sound", "none"],
                       capture_output=True, timeout=10)
    except (OSError, subprocess.SubprocessError):
        pass


def invocation_context() -> dict:
    try:
        return json.loads(os.environ.get("HERDR_PLUGIN_CONTEXT_JSON") or "{}")
    except json.JSONDecodeError:
        return {}


def selected_text() -> str:
    """The selection Herdr passes to the action, else the clipboard."""
    text = invocation_context().get("selected_text")
    if isinstance(text, str) and text.strip():
        return text
    # Herdr copies selections to the clipboard (copy_on_select, on by default). Never read
    # aloud what a password manager put there: they mark it concealed or transient.
    if clipboard_is_secret():
        raise RuntimeError("The clipboard holds a password manager item; Speak won't read it aloud")
    return subprocess.run(["/usr/bin/pbpaste"], capture_output=True, text=True, timeout=5).stdout


SECRET_PASTEBOARD_TYPES = {"org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                           "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"}


def clipboard_is_secret() -> bool:
    """True when the clipboard carries a password manager's concealed or transient marker
    (nspasteboard.org convention, used by 1Password, Bitwarden, Apple Passwords, and others)."""
    script = 'ObjC.import("AppKit"); $.NSPasteboard.generalPasteboard.types.js.map(t => t.js).join("\\n")'
    try:
        types = subprocess.run(["/usr/bin/osascript", "-l", "JavaScript", "-e", script],
                               capture_output=True, text=True, timeout=5).stdout.split()
    except (OSError, subprocess.SubprocessError):
        return True  # can't tell: don't risk reading a secret
    return bool(SECRET_PASTEBOARD_TYPES.intersection(types))


def target_pane() -> str:
    pane = os.environ.get("HERDR_PANE_ID") or invocation_context().get("focused_pane_id")
    if pane:
        return pane
    panes = run_json("pane", "list").get("panes", [])
    focused = [p for p in panes if p.get("focused")]
    if not focused:
        raise RuntimeError("No focused pane")
    return focused[0]["pane_id"]


def agent_info(pane: str) -> dict:
    return run_json("agent", "get", pane).get("agent", {})


def pane_title(pane: str, agent: dict, language: Optional[str] = None) -> str:
    """'Claude in agent-extensions': the agent and its workspace.

    Not the pane label: agents such as Claude Code rewrite it with their current activity.
    """
    kind = str(agent.get("agent") or "")
    name = SUPPORTED_AGENTS.get(kind, kind or "Agent")
    label = None
    try:
        workspaces = run_json("workspace", "list").get("workspaces", [])
        label = next((w.get("label") for w in workspaces if w.get("workspace_id") == agent.get("workspace_id")), None)
    except (RuntimeError, OSError, subprocess.SubprocessError, json.JSONDecodeError):
        pass
    title = f"{name} {catalog.language(language)['in']} {label}" if label else name
    return plain_label(title)  # labels are user text; keep escape sequences out of the panel and tab bar


PANEL_TARGET = "panel-target.json"  # the pane the panel was opened from, for its Play / Prev / Next


def open_panel(target: Optional[str] = None, title: str = "") -> None:
    try:
        paths.STATE_DIR.mkdir(parents=True, exist_ok=True)
        (paths.STATE_DIR / PANEL_TARGET).write_text(json.dumps({"pane": target, "title": title}))
    except OSError:
        pass
    run_json("plugin", "pane", "open", "--plugin", os.environ.get("HERDR_PLUGIN_ID") or "emilapps.speak",
             "--entrypoint", "panel", "--focus")


def agent_target(pane: Optional[str], language: Optional[str] = None) -> Tuple[Optional[str], str]:
    """(pane, title) when the pane runs an agent Speak reads, else (None, "")."""
    if not pane:
        return None, ""
    try:
        agent = agent_info(pane)
    except (RuntimeError, OSError, subprocess.SubprocessError, ValueError):
        return None, ""
    if agent.get("agent") not in SUPPORTED_AGENTS:
        return None, ""
    return pane, pane_title(pane, agent, language)


def panel_target() -> Tuple[Optional[str], str]:
    try:
        saved = json.loads((paths.STATE_DIR / PANEL_TARGET).read_text())
        pane, title = saved.get("pane"), saved.get("title")
    except (OSError, ValueError, AttributeError):
        return None, ""
    return (pane, plain_label(str(title or ""))) if isinstance(pane, str) else (None, "")


def resize_to_rows(pane: str, rows: int) -> None:
    """Best effort: shrink a pane split below another to about `rows` rows (Herdr caps splits at 90%)."""
    try:
        layout = run_json("pane", "layout", "--pane", pane).get("layout", {})
        height = next(p["rect"]["height"] for p in layout.get("panes", []) if p.get("pane_id") == pane)
        parent = max((s["rect"]["height"] for s in layout.get("splits", []) if s.get("direction") == "down"), default=0)
        if parent and height > rows:
            run_json("pane", "resize", "--pane", pane, "--direction", "down", "--amount", f"{(height - rows) / parent:.3f}")
    except (RuntimeError, StopIteration, KeyError, TypeError, OSError, subprocess.SubprocessError):
        pass  # a taller mini player still works
